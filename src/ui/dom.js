// Tiny DOM helper. Text always goes through textContent; handlers through addEventListener;
// styles through element.style (the Content-Security-Policy blocks inline handlers and styles).

/**
 * h('button', { class: 'primary', onClick: fn }, 'label')
 * attrs: class, on<Event> handlers, style (object), any other attribute as a string.
 */
export function h(tag, attrs, ...children) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs || {})) {
    if (v === undefined || v === null || v === false) continue;
    if (k === 'class') el.className = v;
    else if (k === 'style') Object.assign(el.style, v);
    else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2).toLowerCase(), v);
    else if (v === true) el.setAttribute(k, '');
    else el.setAttribute(k, String(v));
  }
  append(el, children);
  return el;
}

function append(el, children) {
  for (const c of children) {
    if (c === null || c === undefined || c === false) continue;
    if (Array.isArray(c)) append(el, c);
    else if (c instanceof Node) el.appendChild(c);
    else el.appendChild(document.createTextNode(String(c)));
  }
}

export function render(root, ...nodes) {
  root.replaceChildren();
  append(root, nodes);
}
